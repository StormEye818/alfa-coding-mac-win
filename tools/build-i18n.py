def main():
    ns = json.load(open(os.path.join(BASE, 'named-settings.json'), encoding='utf-8'))
    fn = json.load(open(os.path.join(BASE, 'functions.json'), encoding='utf-8'))
    md = json.load(open(os.path.join(BASE, 'modules.json'), encoding='utf-8'))

    # 收集所有需要译的字符串
    need = set()
    for s in ns['settings']:
        need.add(s['name'])
        for o in s['options']:
            need.add(o['label'])
    for c in fn['categories']:
        for i in c['items']:
            need.add(i['name'])
    for m in md['modules']:
        need.add(m['name'])

    known = {}
    known.update(TERMS)
    known.update(OPTIONS)
    known.update(MODULES)

    missing = sorted(n for n in need if n not in known)
    # 国家代码占位符统一处理
    for m in list(missing):
        if re.fullmatch(r'Country [0-9A-Fa-f]{2}', m):
            known[m] = f'国家代码 {m.split()[1]}'
            missing.remove(m)

    out = {
        "note": "诊断软件 术语中文对照。zh=译文（汽车行业标准说法），en=原文。用于界面显示；en 保留以便与 诊断软件 对照。",
        "version": "1.0",
        "terms": {k: {"zh": v, "en": k} for k, v in TERMS.items()},
        "options": {k: {"zh": v, "en": k} for k, v in OPTIONS.items()},
        "modules": {k: {"zh": v, "en": k} for k, v in MODULES.items()},
        "categories": {k: v for k, v in CATEGORIES.items()},
        "kinds": KINDS,
    }
    # 国家代码占位
    for k, v in list(known.items()):
        if k not in out['terms'] and k not in out['options'] and k not in out['modules']:
            if re.fullmatch(r'Country [0-9A-Fa-f]{2}', k):
                out['options'][k] = {"zh": v, "en": k}

    with open(os.path.join(BASE, 'i18n.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    total = len(need)
    covered = total - len(missing)
    print(f'需译词条: {total}')
    print(f'已覆盖  : {covered}  ({covered*100//total}%)')
    print(f'未覆盖  : {len(missing)}')
    if missing:
        with open('/tmp/i18n-missing.txt', 'w', encoding='utf-8') as f:
            f.write('\n'.join(missing))
        print('未覆盖清单已写 /tmp/i18n-missing.txt')
        for m in missing[:40]:
            print('  ?', m)


if __name__ == '__main__':
    main()
